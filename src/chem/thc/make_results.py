#!/usr/bin/env python
"""Assemble results/RESULTS.md from the JSON run records and the norms CSV.

Every optimize.py run drops a JSON sidecar; evaluate.py writes the norms CSV. This
joins them on the checkpoint filename so the table can be regenerated at any time
without re-reading optimizer logs.

    python make_results.py                     # writes results/RESULTS.md
    python make_results.py --out somewhere.md
"""

from __future__ import annotations

import argparse
import csv
import glob
import json
import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))


def load(results_dir: str, csv_path: str):
    runs = {}
    for path in sorted(glob.glob(os.path.join(results_dir, "*.json"))):
        record = json.load(open(path))
        if record.get("chk"):
            runs[record["chk"]] = record
    norms = {}
    if os.path.exists(csv_path):
        for row in csv.DictReader(open(csv_path)):
            norms[row["checkpoint"]] = row
    return runs, norms


def fnum(row, key, fmt="{:.5g}"):
    try:
        return fmt.format(float(row[key]))
    except (KeyError, TypeError, ValueError):
        return "--"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--results-dir", default=os.path.join(_HERE, "results"))
    parser.add_argument("--csv", default=os.path.join(_HERE, "results", "optimized_norms.csv"))
    parser.add_argument("--out", default=os.path.join(_HERE, "results", "RESULTS.md"))
    args = parser.parse_args(argv)

    runs, norms = load(args.results_dir, args.csv)
    lines = [
        "# Optimization results",
        "",
        "Generated by `make_results.py` from the JSON run records and `optimized_norms.csv`.",
        "Regenerate after any new run. Absolute values are in the checkpoints' internal units.",
        "",
        "`rel_error` is the optimizer's own fit error against the c=20 reference. It is the",
        "control variable: a lower norm at a worse `rel_error` is not an improvement, so read",
        "the norm columns only between rows at comparable `rel_error`.",
        "",
        "| kmesh | X^v norm | norm_const | power | steps | rel_error | xo_op | xv_op | xv_2inf | w_op | a_embed^op | a_embed^op-mod | a_LCU^dir |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    mesh_key = lambda s: int(s.split("x")[0])
    for chk in sorted(runs, key=lambda c: (mesh_key(runs[c]["kmesh"]),
                                           runs[c]["xv_norm"],
                                           runs[c]["norm_const"])):
        run = runs[chk]
        row = norms.get(chk, {})
        lines.append(
            f"| {run['kmesh']} | {run['xv_norm']} | {run['norm_const']} | {run['power']} | "
            f"{run['adam_steps']} | {run['final_rel_error']:.4g} | "
            f"{fnum(row,'xo_op','{:.4g}')} | {fnum(row,'xv_op','{:.4g}')} | "
            f"{fnum(row,'xv_2inf','{:.4g}')} | {fnum(row,'w_op_max')} | "
            f"{fnum(row,'alpha_embed_op')} | {fnum(row,'alpha_embed_op_mod')} | "
            f"{fnum(row,'alpha_lcu_dir')} |"
        )

    baselines = [c for c in norms if c not in runs]
    if baselines:
        lines += ["", "## Unoptimized baselines", "",
                  "| checkpoint | M | xo_op | xv_op | xv_2inf | a_embed^op | a_embed^op-mod | a_LCU^dir |",
                  "|---|---|---|---|---|---|---|---|"]
        for chk in sorted(baselines):
            row = norms[chk]
            lines.append(
                f"| `{chk}` | {row['M']} | {fnum(row,'xo_op','{:.4g}')} | {fnum(row,'xv_op','{:.4g}')} | "
                f"{fnum(row,'xv_2inf','{:.4g}')} | {fnum(row,'alpha_embed_op')} | "
                f"{fnum(row,'alpha_embed_op_mod')} | {fnum(row,'alpha_lcu_dir')} |"
            )

    lines += ["", f"{len(runs)} optimization runs, {len(baselines)} baselines.", ""]
    os.makedirs(os.path.dirname(os.path.abspath(args.out)) or ".", exist_ok=True)
    with open(args.out, "w") as handle:
        handle.write("\n".join(lines) + "\n")
    print(f"wrote {args.out}: {len(runs)} runs, {len(baselines)} baselines")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
